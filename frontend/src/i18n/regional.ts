// Page <title>/description for each regional page (used in the browser and by prerender.mjs).
export function regionalCutoffMeta(lang: Lang, c: CutoffState) {
  const s = STR[lang];
  const name = stateName(lang, c);
  const open = c.categorySummary.find((x) => x.category === "OPEN");
  const o = open ? s.cutoffDescOpen(s.value(fmtNum(open.last), c.rankType)) : "";
  return { title: s.cutoffTitle(name, c.year), description: s.cutoffDesc(name, c.year, o) };
}
export const regionalCutoffIndexMeta = (lang: Lang) => ({ title: STR[lang].idxTitle, description: STR[lang].idxDesc });
export const regionalWeightageMeta = (lang: Lang) => ({ title: STR[lang].wTitle, description: STR[lang].wDesc });

// hreflang alternates: the English page plus every language version of it.
export function alternates(enPath: string, langs: Lang[], origin: string) {
  return [
    { hreflang: "en", href: `${origin}${enPath}` },
    ...langs.map((l) => ({ hreflang: l, href: `${origin}/${l}${enPath}` })),
    { hreflang: "x-default", href: `${origin}${enPath}` },
  ];
}
